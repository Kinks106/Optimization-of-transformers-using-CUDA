"""
check_correctness.py - Step 3: compare every Triton version with PyTorch.

Reference: torch.nn.functional.scaled_dot_product_attention(..., is_causal=True) in FP32.
Extra column: error against a float64 reference, to show how far each FP32 result
(including SDPA's own) is from the exact answer.

Inputs: Q, K, V independent, uniform in [-1, 1] (same range as our CUDA code), d = 64.

Run from the repo root:
    python triton_attention/check_correctness.py
Writes: triton_attention/results/correctness_<gpu>.md
"""

import importlib
import os
import re
import sys

import torch
import torch.nn.functional as F
import triton

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
tiled = importlib.import_module("01_triton_tiled_qkt")
fused = importlib.import_module("02_triton_fused_attention")

SEQ_LENS = (128, 256, 512, 1024)
HEAD_DIM = 64
SEED = 0

# Make sure no PyTorch FP32 matmul silently uses TF32 (these are already the defaults).
torch.backends.cuda.matmul.allow_tf32 = False
torch.backends.cudnn.allow_tf32 = False

# Pass/fail tolerances (max absolute error vs SDPA FP32)
TOL_FP32 = 1e-5
TOL_FP16 = 1e-2


def sdpa(q, k, v):
    return F.scaled_dot_product_attention(q[None, None], k[None, None], v[None, None],
                                          is_causal=True)[0, 0]


def max_err(a, b):
    return (a.double() - b.double()).abs().max().item()


def main() -> int:
    gpu = torch.cuda.get_device_name(0)
    cap = "sm_%d%d" % torch.cuda.get_device_capability(0)
    header = (f"GPU: {gpu} ({cap}) | torch {torch.__version__} | triton {triton.__version__} | "
              f"d = {HEAD_DIM} | inputs U[-1, 1], seed {SEED}")
    print(header)

    versions = [
        ("Triton tiled (FP32)", lambda q, k, v: tiled.triton_tiled_attention(q, k, v), TOL_FP32),
        ("Triton fused (FP32)", lambda q, k, v: fused.triton_fused_attention(q, k, v), TOL_FP32),
        ("Triton fused FP16 (separate)",
         lambda q, k, v: fused.triton_fused_attention(q.half(), k.half(), v.half()), TOL_FP16),
    ]

    rows = []
    all_ok = True
    for N in SEQ_LENS:
        g = torch.Generator(device="cuda").manual_seed(SEED + N)
        q, k, v = (torch.rand(N, HEAD_DIM, device="cuda", generator=g) * 2 - 1 for _ in range(3))
        ref32 = sdpa(q, k, v)
        ref64 = sdpa(q.double(), k.double(), v.double())  # math backend, float64
        rows.append((N, "PyTorch SDPA (FP32), reference", 0.0, max_err(ref32, ref64), True))
        for name, fn, tol in versions:
            out = fn(q, k, v)
            torch.cuda.synchronize()
            e32 = max_err(out, ref32)
            ok = e32 < tol
            all_ok &= ok
            rows.append((N, name, e32, max_err(out, ref64), ok))

    lines = [
        f"<!-- generated by check_correctness.py -->",
        f"{header}",
        "",
        "| Seq len | Implementation | max abs err vs SDPA FP32 | max abs err vs float64 | Pass |",
        "|---:|---|---:|---:|:---:|",
    ]
    for N, name, e32, e64, ok in rows:
        e32_s = "—" if name.startswith("PyTorch") else f"{e32:.3e}"
        lines.append(f"| {N} | {name} | {e32_s} | {e64:.3e} | {'yes' if ok else 'NO'} |")
    lines += ["", f"Pass = error vs SDPA below {TOL_FP32:g} (FP32) or {TOL_FP16:g} (FP16)."]
    table = "\n".join(lines)
    print()
    print(table)

    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    slug = re.sub(r"[^a-z0-9]+", "_", gpu.lower()).strip("_")
    path = os.path.join(HERE, "results", f"correctness_{slug}.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(table + "\n")
    print(f"\nSaved: {os.path.relpath(path)}")
    print("ALL PASS" if all_ok else "SOME CHECKS FAILED")
    return 0 if all_ok else 1


if __name__ == "__main__":
    sys.exit(main())
